CREATE TABLE users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username varchar(32) NOT NULL UNIQUE,
 password_hash text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE posts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 author_id bigint NOT NULL REFERENCES users(id),
 content varchar(280) NOT NULL CHECK (length(btrim(content)) > 0),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX posts_author_created_idx ON posts(author_id,created_at DESC,id DESC);
CREATE TABLE follows (
 follower_id bigint NOT NULL REFERENCES users(id),
 followed_id bigint NOT NULL REFERENCES users(id),
 PRIMARY KEY(follower_id,followed_id),
 CHECK(follower_id <> followed_id)
);
CREATE TABLE likes (
 post_id bigint NOT NULL REFERENCES posts(id),
 user_id bigint NOT NULL REFERENCES users(id),
 PRIMARY KEY(post_id,user_id)
);
CREATE TABLE comments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 post_id bigint NOT NULL REFERENCES posts(id),
 author_id bigint NOT NULL REFERENCES users(id),
 content varchar(1000) NOT NULL CHECK (length(btrim(content)) > 0),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX comments_post_created_idx ON comments(post_id,created_at DESC,id DESC);
CREATE TABLE benchmark_identity (singleton boolean PRIMARY KEY DEFAULT true CHECK(singleton), identity uuid NOT NULL);
